    private void jbtCalculoAmortActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtCalculoAmortActionPerformed
        // TODO add your handling code here:
    try {
        
        // Obtener los datos
        double monto = Double.parseDouble(jtfCcredito10.getText());
        double interesAnual = Double.parseDouble(jtfInteresMin.getText());
        int meses = Integer.parseInt(jtfPeriodoMax.getText());

        // Convertir interés anual a mensual
        double tasaMensual = (interesAnual / 100) / 12;

        // Variables
        double cuota;
        double saldo = monto;
        double totalIntereses = 0;

        // Calcular la cuota mensual
        if (tasaMensual == 0) {
            cuota = monto / meses;
        } else {
            cuota = monto *
                    (tasaMensual * Math.pow(1 + tasaMensual, meses)) /
                    (Math.pow(1 + tasaMensual, meses) - 1);
        }

        // Limpiar la tabla
        DefaultTableModel modelo =
                (DefaultTableModel) jtablaPrestamo.getModel();

        modelo.setRowCount(0);

        // Crear tabla de amortización
        for (int i = 1; i <= meses; i++) {

            double interes = saldo * tasaMensual;
            double capital = cuota - interes;

            // Evitar saldo negativo
            if (capital > saldo) {
                capital = saldo;
                cuota = capital + interes;
            }

            saldo = saldo - capital;

            totalIntereses += interes;

            // Agregar fila
            modelo.addRow(new Object[]{
                i,
                capital,
                interes,
                cuota,
                saldo
            });
        }

        JOptionPane.showMessageDialog(
                this,
                "Tabla de amortización creada.\n\n"
                + "Total de intereses: "
                + String.format("%.2f", totalIntereses)
        );

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Ingrese correctamente el monto, interés y plazo.",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_jbtCalculoAmortActionPerformed

