    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // Actualizar las variables con los valores de los controles

      try {
    double credito = Double.parseDouble(jtfCcredito10.getText());
    int periodoMin = Integer.parseInt(jtfPerdiodoMin.getText());
    int periodoMax = Integer.parseInt(jtfPeriodoMax.getText());
    double interesMin = Double.parseDouble(jtfInteresMin.getText());
    double interesMax = Double.parseDouble(jtfInteresMax.getText());
    double incremento = Double.parseDouble(jbcIncremento.getSelectedItem().toString());

    // Validaciones
    if (credito <= 0) {
        JOptionPane.showMessageDialog(this, "El crédito debe ser mayor que 0.");
        return;
    }

    if (periodoMin <= 0 || periodoMax < periodoMin) {
        JOptionPane.showMessageDialog(this, "Revise los períodos mínimo y máximo.");
        return;
    }

    if (interesMin < 0 || interesMax < interesMin) {
        JOptionPane.showMessageDialog(this, "Revise los intereses mínimo y máximo.");
        return;
    }

    if (incremento <= 0) {
        JOptionPane.showMessageDialog(this, "El incremento debe ser mayor que 0.");
        return;
    }

    // Crear el modelo de la tabla
    DefaultTableModel modelo = new DefaultTableModel();

    modelo.addColumn("Interés");

    // Crear las columnas de períodos
    for (int periodo = periodoMin; periodo <= periodoMax; periodo++) {

        if (enAnios) {
            modelo.addColumn(periodo + " año(s)");
        } else {
            modelo.addColumn(periodo + " mes(es)");
        }
    }

    // Calcular los pagos
    for (double interes = interesMin;
         interes <= interesMax + 0.0001;
         interes += incremento) {

        Object[] fila = new Object[periodoMax - periodoMin + 2];

        fila[0] = String.format("%.2f%%", interes);

        int columna = 1;

        for (int periodo = periodoMin;
             periodo <= periodoMax;
             periodo++) {

            int meses;

            if (enAnios) {
                meses = periodo * 12;
            } else {
                meses = periodo;
            }

            double interesMensual = interes / 100.0 / 12.0;

            double pago;

            if (interesMensual == 0) {
                pago = credito / meses;
            } else {
                pago = (credito * interesMensual)
                        / (1 - Math.pow(1 + interesMensual, -meses));
            }

            fila[columna] = String.format("%.2f", pago);

            columna++;
        }

        modelo.addRow(fila);
    }

    // Mostrar los resultados en la tabla
    jtablaPrestamo.setModel(modelo);

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(
        this,
        "Revise que todos los datos numéricos estén escritos correctamente.",
        "Error",
        JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_jButton1ActionPerformed

